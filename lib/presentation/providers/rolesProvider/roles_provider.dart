import 'dart:convert';

import 'package:gestbanda/domain/newmodels/roleModels/role_dto.dart';
import 'package:gestbanda/domain/newmodels/roleModels/role_provider_dto.dart';
import 'package:gestbanda/presentation/providers/errorProvider/error_provider.dart';
import 'package:gestbanda/presentation/providers/sharedPreferencesProvider/shared_preferences_provider.dart';
import 'package:riverpod_annotation/riverpod_annotation.dart';
import 'package:http/http.dart' as http;

import '../../../domain/newmodels/bandModels/band_dto.dart';
import '../../../domain/newmodels/userModels/user_dto.dart';
import '../../../domain/newmodels/voiceModels/voice_dto.dart';
import '../../../config/api_config.dart';

part 'roles_provider.g.dart';

/// A provider class that manages roles data and operations related to roles.
/// It extends the _$RolesProvider class generated by Riverpod and contains
/// methods to fetch roles, user, and band information.
@riverpod
class RolesProvider extends _$RolesProvider {
  /// Initializes the state of the RolesProvider with default values.
  /// This includes an empty list of roles, loading status, and default user and band information.
  @override
  RoleProviderDTO build() => RoleProviderDTO(
        roles: [],
        isLoading: false,
        user: UserDTO(
            id: "",
            email: "",
            token: "",
            name: "",
            phone: "",
            img: "",
            role: RoleDTO(id: "", name: "", router: ""),
            voz: VoiceDTO(id: "", name: ""),
            instrumentList: [],
            costumeList: []),
        band: BandDTO(
            id: "",
            name: "",
            img: "",
            subscriptionID: "",
            substriptionEndDate: DateTime.now()),
      );

  /// Fetches the list of roles from the API.
  /// It checks if a loading process is already underway to prevent multiple calls.
  /// Upon success, it updates the state with the retrieved roles.
  /// If an error occurs, it will set the appropriate error message.
  Future<void> getRolesList() async {
    const api = apiUrl;

    if (state.isLoading) return;

    // Start loading
    state.isLoading = true;

    await getUser();
    await getBand();
    try {
      final response = await http.get(
        Uri.parse("$api/roles/getAllRoles"),
        headers: <String, String>{
          'Content-Type': 'application/json',
          'Authorization': state.user.token,
        },
      );

      if (response.statusCode == 200) {
        final jsonResponse = jsonDecode(response.body);

        if (jsonResponse is List) {
          final List<RoleDTO> listRoles = jsonResponse
              .map((jsonItem) => RoleDTO.fromJson(jsonItem))
              .toList();

          state = state.copyWith(roles: listRoles);
        } else {
          ref
              .read(errorProviderProvider.notifier)
              .setError("El formato de respuesta no es una lista.");
        }
      } else {
        final data = json.decode(response.body);
        ref
            .read(errorProviderProvider.notifier)
            .setError(data["message"].toString());
      }
    } catch (e) {
      ref.read(errorProviderProvider.notifier).setError(
          "Ha ocurrido un error en la aplicacion. Intentalo más tarde.");
    } finally {
      state.copyWith(isLoading: false);
    }
  }

  /// Retrieves the current user from SharedPreferences and updates the state.
  /// If the user is not found, an error is set in the error provider.
  Future<void> getUser() async {
    String? userJSON = await ref
        .read(sharedPreferencesProviderProvider.notifier)
        .getString(key: 'user');

    if (userJSON != null) {
      state = state.copyWith(user: UserDTO.fromJson(jsonDecode(userJSON)));
    } else {
      ref
          .read(errorProviderProvider.notifier)
          .setError("No se ha encontrado la sesión del usuario.");
    }
  }

  /// Retrieves the current band from SharedPreferences and updates the state.
  /// If the band is not found, an error is set in the error provider.
  Future<void> getBand() async {
    String? bandJSON = await ref
        .read(sharedPreferencesProviderProvider.notifier)
        .getString(key: 'band');

    if (bandJSON != null) {
      state = state.copyWith(band: BandDTO.fromJson(jsonDecode(bandJSON)));
    } else {
      ref
          .read(errorProviderProvider.notifier)
          .setError("No se ha encontrado la banda en la sesión.");
    }
  }
}
